fairness = load_report("fairness_summary.csv")
age = load_report("age_fairness_report.csv")
gender = load_report("gender_fairness_report.csv")
explain = load_report("explainability_report.csv")

def report(df, filename):
    if df.empty:
        st.warning("Report not found.")
        return
    st.dataframe(df, use_container_width=True)
    st.download_button(
        "Download CSV",
        df.to_csv(index=False),
        filename,
        "text/csv"
    )

def chart(df, x, y, title):
    if not df.empty and x in df.columns and y in df.columns:
        st.subheader(title)
        data = df.groupby(x)[y].mean()
        st.bar_chart(data)

