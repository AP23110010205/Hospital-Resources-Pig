import streamlit as st
import pandas as pd
from pathlib import Path

st.set_page_config(
    page_title="Hospital Resource Management",
    page_icon="🏥",
    layout="wide"
)

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
DATA = ROOT / "data" / "raw" / "hospital_resources.csv"

def load_report(name):
    path = RESULTS / name
    if path.exists():
        return pd.read_csv(path)
    return pd.DataFrame()

st.markdown("""
<style>
.stApp {background:#f4f7fb;}
[data-testid="stSidebar"] {background:#102b46;}
[data-testid="stSidebar"] * {color:white;}
h1 {color:#123b5d;}
</style>
""", unsafe_allow_html=True)

st.sidebar.title("🏥 HOSPITAL ANALYTICS")
st.sidebar.caption("BIG DATA RESOURCE MANAGEMENT")
st.sidebar.divider()

